# Firmware-enforced setup lifecycle (v3.1.0). Hardware pins/PWM remain fixed.
def _setup_group(name, fields, writable=False, persistent=False):
    return {'name':name,'schema':1,'persistent':persistent,
            'access':'read_write_save' if writable and persistent else 'read',
            'fields':[dict(index=i,**field) for i,field in enumerate(fields)]}

def _integer(name, minimum=0, maximum=4294967295, default=0):
    return dict(name=name,type='int',min=minimum,max=maximum,default=default)

def _boolean(name, default=False):return dict(name=name,type='bool',default=default)

